"""Build the Windows x64 launcher, offline component archives and release catalog."""

import argparse
import csv
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import struct
import subprocess
import sys
from tempfile import TemporaryDirectory
from urllib.parse import urlsplit
from urllib.request import urlopen
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo


REPO = Path(__file__).resolve().parents[1]
LOCK = Path(__file__).with_name('portable-inputs.json')
PYTHON_VERSION = '3.12.10'
QT_VERSION = '6.11.2'
FFMPEG_VERSION = '8.0.1'
MODEL_VERSION = 'v3.4-weights'
ORT_VERSION = '1.22.0'
PYINSTALLER_VERSION = '6.17.0'

QT_WHEELS = ('PySide6', 'PySide6-Essentials', 'PySide6-Addons', 'shiboken6')
DETECTOR_WHEELS = ('numpy', 'opencv-python-headless', 'coloredlogs', 'humanfriendly', 'pyreadline3',
                   'flatbuffers', 'packaging', 'protobuf', 'sympy', 'mpmath')
CUDA_WHEELS = ('nvidia-cuda-runtime-cu12', 'nvidia-cuda-nvrtc-cu12', 'nvidia-cufft-cu12',
               'nvidia-curand-cu12', 'nvidia-cublas-cu12', 'nvidia-cudnn-cu12', 'nvidia-nvjitlink-cu12')
COMPONENTS = ('base', 'ffmpeg', 'cpu', 'gpu', '320n', '640m')


def sha256(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def fetch(name, entry, cache, offline):
    path = cache / name
    if path.is_file() and sha256(path) == entry['sha256']:
        return path
    if offline:
        raise ValueError(f'{name} is missing or failed its SHA-256 check in {cache}')
    temporary = path.with_name(path.name + '.partial')
    print(f'Downloading {name}', flush=True)
    try:
        with urlopen(entry['url'], timeout=60) as response, temporary.open('wb') as output:
            shutil.copyfileobj(response, output, length=1024 * 1024)
        if sha256(temporary) != entry['sha256']:
            raise ValueError(f'SHA-256 mismatch for {name}')
        temporary.replace(path)
        return path
    finally:
        temporary.unlink(missing_ok=True)


def write_zip(source, output):
    temporary = output.with_name(output.name + '.partial')
    try:
        with ZipFile(temporary, 'w', compression=ZIP_DEFLATED, compresslevel=6) as archive:
            for path in sorted(source.rglob('*')):
                if not path.is_file():
                    continue
                info = ZipInfo(path.relative_to(source).as_posix(), (1980, 1, 1, 0, 0, 0))
                info.compress_type = ZIP_DEFLATED
                info.external_attr = 0o100644 << 16
                info.file_size = path.stat().st_size
                with path.open('rb') as stream, archive.open(info, 'w') as member:
                    shutil.copyfileobj(stream, member, length=1024 * 1024)
        temporary.replace(output)
    finally:
        temporary.unlink(missing_ok=True)


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def install_wheels(wheels, target):
    # Pin every wheel explicitly and avoid embedded build paths in generated bytecode.
    subprocess.run([sys.executable, '-m', 'pip', '--isolated', 'install', '--no-index',
                    '--no-deps', '--no-compile', '--disable-pip-version-check',
                    '--target', str(target), *map(str, wheels)], check=True)
    # Console scripts are unused and contain the build machine's Python path.
    for name in ('bin', 'Scripts'):
        path = target / name
        if path.is_dir():
            shutil.rmtree(path)
    # pip records the absolute wheel cache path for direct installs.
    for metadata in target.glob('*.dist-info'):
        (metadata / 'direct_url.json').unlink(missing_ok=True)
        record = metadata / 'RECORD'
        with record.open(encoding='utf-8', newline='') as stream:
            entries = [entry for entry in csv.reader(stream)
                       if not entry[0].endswith('/direct_url.json') and not entry[0].startswith('../')]
        with record.open('w', encoding='utf-8', newline='') as stream:
            csv.writer(stream, lineterminator='\n').writerows(sorted(entries))


def stage_component(component, stage, lock, cache, offline):
    def asset(name):
        return fetch(name, lock['assets'][name], cache, offline)

    wheels = ()
    if component == 'base':
        with ZipFile(asset(f'python-{PYTHON_VERSION}-embed-amd64.zip')) as archive:
            archive.extractall(stage)
        (stage / 'python312._pth').write_bytes(b'python312.zip\n.\napp\nsite-packages\n')
        shutil.copytree(REPO / 'q_pixelate', stage / 'app' / 'q_pixelate',
                        ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
        wheels = QT_WHEELS
    elif component == 'ffmpeg':
        release_name = f'ffmpeg-{FFMPEG_VERSION}-essentials_build'
        with ZipFile(asset(f'{release_name}.zip')) as archive:
            for name in ('bin/ffmpeg.exe', 'bin/ffprobe.exe', 'LICENSE', 'README.txt'):
                target = stage / name
                target.parent.mkdir(parents=True, exist_ok=True)
                with archive.open(f'{release_name}/{name}') as source, target.open('wb') as output:
                    shutil.copyfileobj(source, output, length=1024 * 1024)
    elif component in ('cpu', 'gpu'):
        wheels = ('onnxruntime', *DETECTOR_WHEELS) if component == 'cpu' else (
            'onnxruntime-gpu', *DETECTOR_WHEELS, *CUDA_WHEELS)
    else:
        weights = stage / 'weights.onnx'
        if component == '320n':
            with ZipFile(asset('nudenet-3.4.2-py3-none-any.whl')) as archive:
                with archive.open('nudenet/320n.onnx') as source, weights.open('wb') as output:
                    shutil.copyfileobj(source, output, length=1024 * 1024)
        else:
            shutil.copyfile(asset('640m.onnx'), weights)
        shutil.copyfile(asset('NudeNet-LICENSE'), stage / 'LICENSE')
    if wheels:
        wheel_entries = [lock['wheels'][name] for name in wheels]
        site_packages = stage / 'site-packages'
        install_wheels([fetch(entry['filename'], entry, cache, offline) for entry in wheel_entries], site_packages)
        if component == 'base':
            # Native recognition packages use the same app-local C++ runtime as Qt.
            for name in ('msvcp140.dll', 'msvcp140_1.dll', 'msvcp140_2.dll', 'vcomp140.dll'):
                shutil.copyfile(site_packages / 'PySide6' / name, stage / name)


def build_launcher(output, work):
    from importlib.metadata import distribution

    builder = distribution('PyInstaller')
    if builder.version != PYINSTALLER_VERSION:
        raise ValueError(f'Install PyInstaller=={PYINSTALLER_VERSION} in the build environment.')
    work.mkdir(parents=True, exist_ok=True)
    command = [sys.executable, '-m', 'PyInstaller', '--noconfirm', '--clean', '--onefile',
               '--windowed', '--noupx', '--name', 'Q-Pixelate', '--distpath', str(output),
               '--workpath', str(work / 'work'), '--specpath', str(work),
               '--exclude-module', 'PySide6', '--exclude-module', 'numpy',
               '--exclude-module', 'onnxruntime', '--exclude-module', 'cv2',
               '--add-data', f'{REPO / "q_pixelate" / "detector_worker.py"}:q_pixelate',
               str(REPO / 'launcher.py')]
    env = os.environ.copy()
    env['PYINSTALLER_CONFIG_DIR'] = str(work / 'cache')
    env.setdefault('SOURCE_DATE_EPOCH', '0')
    env.setdefault('PYTHONHASHSEED', '0')
    subprocess.run(command, cwd=REPO, env=env, check=True)
    licenses = output / 'launcher-licenses'
    licenses.mkdir(exist_ok=True)
    for path in builder.files or ():
        if path.name == 'COPYING.txt':
            shutil.copyfile(path.locate(), licenses / 'PyInstaller-COPYING.txt')
            break
    stdlib_license = Path(sys.base_prefix) / 'LICENSE.txt'
    if stdlib_license.is_file():
        shutil.copyfile(stdlib_license, licenses / 'CPython-LICENSE.txt')
    tk_license = Path(sys.base_prefix) / 'tcl' / 'tk8.6' / 'license.terms'
    if tk_license.is_file():
        shutil.copyfile(tk_license, licenses / 'Tk-license.terms')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base-url', default='', help='HTTP(S) directory that will host the component ZIPs')
    parser.add_argument('--output', type=Path, default=REPO / 'dist' / 'portable')
    parser.add_argument('--cache', type=Path, default=REPO / 'build' / 'portable-inputs')
    parser.add_argument('--components', nargs='*', choices=COMPONENTS, default=COMPONENTS)
    parser.add_argument('--skip-launcher', action='store_true')
    parser.add_argument('--offline', action='store_true', help='Require all inputs in the local cache')
    args = parser.parse_args()
    if (sys.platform != 'win32' or platform.machine().upper() != 'AMD64'
            or struct.calcsize('P') != 8 or sys.version_info[:2] != (3, 12)):
        parser.error('Build with Windows x64 Python 3.12.')
    if args.base_url:
        url = urlsplit(args.base_url)
        if url.scheme not in ('http', 'https') or not url.netloc or url.query or url.fragment:
            parser.error('--base-url must be an HTTP(S) directory URL')
    args.output = args.output.resolve()
    args.cache = args.cache.resolve()
    args.output.mkdir(parents=True, exist_ok=True)
    args.cache.mkdir(parents=True, exist_ok=True)
    if not args.skip_launcher:
        build_launcher(args.output, REPO / 'build' / 'portable-launcher')
    if not args.components:
        return
    sys.path.insert(0, str(REPO))
    from q_pixelate import __version__

    versions = {'base': __version__, 'ffmpeg': FFMPEG_VERSION, 'cpu': ORT_VERSION,
                'gpu': f'{ORT_VERSION}-cuda12', '320n': MODEL_VERSION, '640m': MODEL_VERSION}
    requires = {'cpu': ['base'], 'gpu': ['base']}
    lock = json.loads(LOCK.read_text(encoding='utf-8'))
    entries = {}
    for component in dict.fromkeys(args.components):
        version = versions[component]
        filename = f'q-pixelate-{component}-{version}-win-x64.zip'
        output = args.output / filename
        print(f'Building {filename}', flush=True)
        with TemporaryDirectory(prefix=f'{component}-', dir=args.cache) as staging:
            stage = Path(staging)
            stage_component(component, stage, lock, args.cache, args.offline)
            write_zip(stage, output)
        entries[component] = {
            'version': version,
            'architecture': 'win-x64',
            'dependencies': requires.get(component, []),
            'archive': filename,
            'url': f'{args.base_url.rstrip("/")}/{filename}' if args.base_url else '',
            'size': output.stat().st_size,
            'sha256': sha256(output),
        }
    write_json(args.output / 'component-catalog.json', {'architecture': 'win-x64', 'components': entries})
    for name in ('README.md', 'portable-inputs.json'):
        shutil.copyfile(Path(__file__).with_name(name), args.output / name)


if __name__ == '__main__':
    main()
